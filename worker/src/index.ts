/**
 * GET /tts/voices?provider=… → the voices the app may offer for that provider.
 * Only ElevenLabs is listed here: the Cartesia voices are built into the app
 * (WaitWhatVoice) and stay as they are.
 */
function handleListTextToSpeechVoices(providerQuery: string | null): Response {
  const provider = providerQuery === "elevenlabs" ? "elevenlabs" : "cartesia";
  if (provider !== "elevenlabs") {
    return jsonResponse({ error: "only provider=elevenlabs is listed by the worker" }, 400);
  }
  return new Response(JSON.stringify({ provider, model_id: ELEVENLABS_MODEL_ID, voices: ELEVENLABS_CURATED_VOICES }), {
    headers: {
      "content-type": "application/json",
      // A hardcoded list: let the app cache it for the session.
      "cache-control": "public, max-age=3600",
    },
  });
}

