type TextToSpeechProvider = "cartesia" | "elevenlabs";

/**
 * Body: { text, voice_id?, speed?, provider? }. Extra fields are ignored, so
 * older app builds that send extra voice settings keep working. Both
 * providers answer with the same MP3 (44.1 kHz, 128 kbps), so the app's
 * player never needs to know which one spoke.
 */
interface TextToSpeechRequestBody {
  text: string;
  voice_id?: string;
  speed?: number;
  provider?: string;
}

async function handleTextToSpeech(request: Request, env: Env): Promise<Response> {
  const body = (await request.json()) as TextToSpeechRequestBody;
  const provider: TextToSpeechProvider = body.provider === "elevenlabs" ? "elevenlabs" : "cartesia";

  if (provider === "elevenlabs") {
    if (!env.ELEVENLABS_API_KEY) {
      return jsonResponse({ error: "ELEVENLABS_API_KEY is not set on the worker" }, 500);
    }
    return await handleTTSWithElevenLabs(body, env);
  }

  if (!env.CARTESIA_API_KEY) {
    return jsonResponse({ error: "CARTESIA_API_KEY is not set on the worker" }, 500);
  }
  return await handleTTSWithCartesia(body, env);
}

async function handleTTSWithCartesia(body: TextToSpeechRequestBody, env: Env): Promise<Response> {
  const text = body.text;
  const voiceId = body.voice_id || env.CARTESIA_VOICE_ID || "db6b0ed5-d5d3-463d-ae85-518a07d3c2b4";
  // Cartesia accepts generation_config.speed in [0.6, 1.5]; clamp whatever the app sends.
  const speed = typeof body.speed === "number" ? Math.min(1.5, Math.max(0.6, body.speed)) : undefined;

  const response = await fetch("https://api.cartesia.ai/tts/bytes", {
    method: "POST",
    headers: {
      "x-api-key": env.CARTESIA_API_KEY!,
      "cartesia-version": "2026-08-14",
      "content-type": "application/json",
    },
    body: JSON.stringify({
      model_id: "sonic-3.6",
      transcript: text,
      voice: { mode: "id", id: voiceId },
      language: "en",
      ...(speed !== undefined ? { generation_config: { speed } } : {}),
      output_format: { container: "mp3", sample_rate: 44100, bit_rate: 128000 },
    }),
  });

  if (!response.ok) {
    const errorBody = await response.text();
    console.error(`[/tts] Cartesia API error ${response.status}: ${errorBody}`);
    return new Response(errorBody, {
      status: response.status,
      headers: { "content-type": "application/json" },
    });
  }

  return new Response(response.body, {
    status: 200,
    headers: { "content-type": "audio/mpeg" },
  });
}

