/**
 * hoot-worker: the one place hoot's API keys live. The macOS app only ever
 * talks to this worker, so no secret ships inside the app bundle.
 *
 * Routes:
 *   POST /chat             → Anthropic Messages API (streaming SSE passthrough),
 *                            or OpenAI Chat Completions translated back into
 *                            Anthropic-format SSE when BRAIN=openai
 *   POST /tts              → MP3 bytes. Body: { text, voice_id?, speed?, provider? }
 *                            provider "cartesia" (default) → Cartesia sonic-3.6;
 *                            provider "elevenlabs" → ElevenLabs eleven_flash_v2_5
 *   GET  /tts/voices?provider=elevenlabs → { provider, voices: [{ id, name }] } (curated list, no key needed)
 *   POST /transcribe-token → short-lived AssemblyAI v3 streaming token (JSON from AssemblyAI)
 *   GET  /youtube/:videoId/transcript → { videoId, languageCode, isAutoGenerated, segments: [{ start, duration, text }] }
 */

interface Env {
  ANTHROPIC_API_KEY?: string;
  ASSEMBLYAI_API_KEY?: string;
  CARTESIA_API_KEY?: string;
  CARTESIA_VOICE_ID?: string;
  ELEVENLABS_API_KEY?: string;
  // "anthropic" (default) or "openai". Lets us switch brains without rebuilding the app.
  BRAIN?: string;
  OPENAI_API_KEY?: string;
  OPENAI_MODEL?: string;
}

export default {
  async fetch(request: Request, env: Env): Promise<Response> {
    const requestUrl = new URL(request.url);

    // The transcript route is the only GET route, and its path carries the video id.
    const youtubeTranscriptPathMatch = requestUrl.pathname.match(/^\/youtube\/([A-Za-z0-9_-]{11})\/transcript$/);
    if (youtubeTranscriptPathMatch) {
      if (request.method !== "GET") {
        return jsonResponse({ error: "method not allowed" }, 405);
      }
      return await runRouteHandlerReportingErrors("/youtube/transcript", () =>
        handleYouTubeTranscript(youtubeTranscriptPathMatch[1])
      );
    }

    // The voice list is the other GET route; the app reads it to fill the
    // voice picker without ever holding a TTS key.
    if (requestUrl.pathname === "/tts/voices") {
      if (request.method !== "GET") {
        return jsonResponse({ error: "method not allowed" }, 405);
      }
      return handleListTextToSpeechVoices(requestUrl.searchParams.get("provider"));
    }

    if (request.method !== "POST") {
      return jsonResponse({ error: "method not allowed" }, 405);
    }

    switch (requestUrl.pathname) {
      case "/chat":
        return await runRouteHandlerReportingErrors("/chat", () =>
          env.BRAIN === "openai" ? handleChatWithOpenAI(request, env) : handleChatWithAnthropic(request, env)
        );
      case "/tts":
        return await runRouteHandlerReportingErrors("/tts", () => handleTextToSpeech(request, env));
      case "/transcribe-token":
        return await runRouteHandlerReportingErrors("/transcribe-token", () => handleTranscribeToken(env));
      default:
        return jsonResponse({ error: "not found" }, 404);
    }
  },
};

/** Any thrown error becomes a 502 with a JSON body, so the app can show what went wrong instead of a bare failure. */
async function runRouteHandlerReportingErrors(
  routeNameForLogs: string,
  routeHandler: () => Promise<Response>
): Promise<Response> {
  try {
    return await routeHandler();
  } catch (error) {
    console.error(`[${routeNameForLogs}] unhandled error:`, error);
    return jsonResponse({ error: String(error) }, 502);
  }
}

