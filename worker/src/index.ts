/**
 * The app opens AssemblyAI's streaming websocket itself (audio never passes
 * through the worker), so it needs a temporary token instead of the real key.
 * 480s covers a long push-to-talk plus connection setup.
 */
async function handleTranscribeToken(env: Env): Promise<Response> {
  if (!env.ASSEMBLYAI_API_KEY) {
    return jsonResponse({ error: "ASSEMBLYAI_API_KEY is not set on the worker" }, 500);
  }
  const assemblyTokenResponse = await fetch("https://streaming.assemblyai.com/v3/token?expires_in_seconds=480", {
    method: "GET",
    headers: { authorization: env.ASSEMBLYAI_API_KEY },
  });
  const assemblyTokenResponseBody = await assemblyTokenResponse.text();
  if (!assemblyTokenResponse.ok) {
    console.error(`[/transcribe-token] AssemblyAI error ${assemblyTokenResponse.status}: ${assemblyTokenResponseBody}`);
  }
  return new Response(assemblyTokenResponseBody, {
    status: assemblyTokenResponse.status,
    headers: { "content-type": "application/json" },
  });
}

