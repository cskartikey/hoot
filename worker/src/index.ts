/**
 * Forwards the app's Anthropic Messages body untouched and streams the
 * response body straight back, so SSE events reach the app as Anthropic sends them.
 */
async function handleChatWithAnthropic(request: Request, env: Env): Promise<Response> {
  if (!env.ANTHROPIC_API_KEY) {
    return jsonResponse({ error: "ANTHROPIC_API_KEY is not set on the worker" }, 500);
  }
  const anthropicRequestBodyText = await request.text();

  const anthropicResponse = await fetch("https://api.anthropic.com/v1/messages", {
    method: "POST",
    headers: {
      "x-api-key": env.ANTHROPIC_API_KEY,
      "anthropic-version": "2023-06-01",
      "content-type": "application/json",
    },
    body: anthropicRequestBodyText,
  });

  if (!anthropicResponse.ok) {
    const anthropicErrorBody = await anthropicResponse.text();
    console.error(`[/chat] Anthropic API error ${anthropicResponse.status}: ${anthropicErrorBody}`);
    return new Response(anthropicErrorBody, {
      status: anthropicResponse.status,
      headers: { "content-type": "application/json" },
    });
  }

  return new Response(anthropicResponse.body, {
    status: 200,
    headers: {
      "content-type": anthropicResponse.headers.get("content-type") ?? "text/event-stream",
      "cache-control": "no-cache",
    },
  });
}

/**
 * Takes the app's Anthropic-format request, sends it to OpenAI Chat Completions,
 * and answers in Anthropic format (SSE content_block_delta events when streaming),
 * so the app's ClaudeAPI client works unchanged.
 */
async function handleChatWithOpenAI(request: Request, env: Env): Promise<Response> {
  const anthropicRequest = (await request.json()) as AnthropicRequest;

  const openAIMessages: unknown[] = [];
  if (anthropicRequest.system) {
    openAIMessages.push({ role: "system", content: anthropicRequest.system });
  }
  for (const message of anthropicRequest.messages) {
    openAIMessages.push({
      role: message.role,
      content: typeof message.content === "string"
        ? message.content
        : message.content.map(toOpenAIContentBlock),
    });
  }

  const isStreaming = anthropicRequest.stream === true;
  const response = await fetch("https://api.openai.com/v1/chat/completions", {
    method: "POST",
    headers: {
      authorization: `Bearer ${env.OPENAI_API_KEY}`,
      "content-type": "application/json",
    },
    body: JSON.stringify({
      model: env.OPENAI_MODEL || "gpt-6.1-sol",
      messages: openAIMessages,
      // Reasoning tokens count against this limit, so leave headroom over the app's max_tokens.
      max_completion_tokens: Math.max(anthropicRequest.max_tokens * 2, 2048),
      reasoning_effort: "low",
      stream: isStreaming,
    }),
  });

  if (!response.ok) {
    const errorBody = await response.text();
    console.error(`[/chat] OpenAI API error ${response.status}: ${errorBody}`);
    return new Response(errorBody, {
      status: response.status,
      headers: { "content-type": "application/json" },
    });
  }

  if (!isStreaming) {
    const completion = (await response.json()) as { choices: { message: { content: string } }[] };
    const text = completion.choices[0]?.message?.content ?? "";
    return new Response(JSON.stringify({ content: [{ type: "text", text }] }), {
      headers: { "content-type": "application/json" },
    });
  }

  const encoder = new TextEncoder();
  const decoder = new TextDecoder();
  let bufferedText = "";
  const translateStream = new TransformStream<Uint8Array, Uint8Array>({
    transform(chunk, controller) {
      bufferedText += decoder.decode(chunk, { stream: true });
      const lines = bufferedText.split("\n");
      bufferedText = lines.pop() ?? "";
      for (const line of lines) {
        if (!line.startsWith("data: ")) continue;
        const payload = line.slice(6).trim();
        if (payload === "[DONE]") {
          controller.enqueue(encoder.encode(`data: ${JSON.stringify({ type: "message_stop" })}\n\n`));
          continue;
        }
        try {
          const event = JSON.parse(payload) as { choices?: { delta?: { content?: string } }[] };
          const textChunk = event.choices?.[0]?.delta?.content;
          if (textChunk) {
            const anthropicEvent = { type: "content_block_delta", index: 0, delta: { type: "text_delta", text: textChunk } };
            controller.enqueue(encoder.encode(`data: ${JSON.stringify(anthropicEvent)}\n\n`));
          }
        } catch {
          // Ignore keep-alives and partial lines
        }
      }
    },
  });

  return new Response(response.body!.pipeThrough(translateStream), {
    headers: { "content-type": "text/event-stream", "cache-control": "no-cache" },
  });
}

interface AnthropicContentBlock {
  type: string;
  text?: string;
  source?: { type: string; media_type: string; data: string };
}

interface AnthropicRequest {
  system?: string;
  max_tokens: number;
  stream?: boolean;
  messages: { role: string; content: string | AnthropicContentBlock[] }[];
}

function toOpenAIContentBlock(block: AnthropicContentBlock): unknown {
  if (block.type === "image" && block.source) {
    return {
      type: "image_url",
      image_url: { url: `data:${block.source.media_type};base64,${block.source.data}` },
    };
  }
  return { type: "text", text: block.text ?? "" };
}

